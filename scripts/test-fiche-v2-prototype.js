#!/usr/bin/env node
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert');
const ROOT=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const renderer=read('fiche-corpus-v2.js');
const html=read('fiche.html');
const css=read('maca-fiche-v2-prototype.css');
new vm.Script(renderer,{filename:'fiche-corpus-v2.js'});
assert(renderer.includes("const PROTOTYPE_ID='intolerance-gluten-tests-coeliaque-allergie-ble'"),'prototype ID missing');
assert(renderer.includes('if(String(q.id)===PROTOTYPE_ID){renderPrototype(q,canonical);return;}'),'prototype gate missing');
assert(renderer.includes("document.body.classList.add('maca-fiche-v2-prototype')"),'prototype class missing');
assert(renderer.includes('class="answer-block"'),'generic renderer missing');
assert(html.includes('maca-fiche-v2-prototype.css?v=20260908-proto1'),'prototype CSS not loaded');
assert(html.includes('fiche-corpus-v2.js?v=20260908-proto1'),'prototype renderer cache-bust missing');
assert(css.includes('body.maca-fiche-v2-prototype .maca-fv2-hero'),'scoped hero CSS missing');
assert(css.includes('@media(max-width:560px)'),'mobile breakpoint missing');
assert(renderer.includes('navigator.share'),'native share missing');
assert(renderer.includes('navigator.clipboard'),'share fallback missing');
const manifestSandbox={window:{}};
vm.runInNewContext(read('corpus-manifest.js'),manifestSandbox,{filename:'corpus-manifest.js'});
const files=manifestSandbox.window.MACA_CORPUS_MANIFEST.map(x=>String(x).split('?')[0]);
const ctx={console,setTimeout,clearTimeout,setInterval,clearInterval};ctx.window=ctx;ctx.globalThis=ctx;vm.createContext(ctx);
for(const f of files)vm.runInContext(read(f),ctx,{filename:f});
vm.runInContext(read('corpus-canonicalizer.js'),ctx,{filename:'corpus-canonicalizer.js'});
const items=Array.from(ctx.MACA_BUILD_CANONICAL_CORPUS());
const q=items.find(x=>x&&x.id==='intolerance-gluten-tests-coeliaque-allergie-ble');
assert(q,'canonical coeliac/gluten fiche missing');
assert(String(q.answer||'').trim(),'canonical answer missing');
assert(String(q.detail||'').trim(),'canonical detail missing');
assert(String(q.watch||'').trim(),'canonical vigilance block missing');
assert((Array.isArray(q.sources)&&q.sources.length)||String(q.source||'').trim(),'canonical sources missing');
const other=items.find(x=>x&&x.id&&x.id!==q.id);
assert(other,'comparison fiche missing');
console.log(JSON.stringify({ok:true,targetId:q.id,title:q.title,category:q.category,hasAnswer:true,hasDetail:true,hasWatch:true,sourceCount:Array.isArray(q.sources)?q.sources.length:0,comparisonId:other.id,rendererSyntax:'ok',scopedCss:true,mobileBreakpoint:true,share:true},null,2));
